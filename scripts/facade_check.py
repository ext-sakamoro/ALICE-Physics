#!/usr/bin/env python3
"""The alice-physics facade (crates/alice-physics) is the API of alice-physics-core under the
alice_physics paths. Checked here:

  1. features: the facade's [features] are the core's, both ways, each forwarding exactly
     `alice_physics_core/<the same name>` (default: the same list);
  1b. the facade's dependency on the engine is `version = "=<the engine's version>"`;
  2. the facade's src/lib.rs defines nothing: its only item is `pub use alice_physics_core::*;`
     (attributes and doc comments aside);
  3. paths: crates/alice-physics/tests/facade_paths.rs imports every importable item of the
     core's public API (docs/PUBLIC_API_SNAPSHOT.txt: modules, and the structs, enums, traits,
     unions, type aliases, constants, statics, free functions and re-exports of a module) through
     `alice_physics::<path>`; `--write` regenerates it, the check compares it with what the
     snapshot gives. The test is compiled with the snapshot's features (CI and preflight run
     `cargo test -p alice-physics --features <NATIVE>`), so a path that does not resolve
     through the facade is a compile error.

  4. the pinned identifier the facade's identity test holds (crates/alice-physics/tests/
     facade_identity.rs, copied so it builds from the published package) is the engine's pin
     (tests/physics_semantics_id.rs `PINNED_ID_HEX`);
  5. the engine bindings load the facade's library: the Unity C# binding's `DLL` name and
     the library files the Unreal plugin's Build.cs names are the facade's lib name;
  6. `--build-features`: `cargo check -p alice-physics --lib --features <name>` for every
     feature of the facade but `default` (each forwarded feature builds through the facade).

Exit 1 on a finding, 2 when it compared nothing.

    python3 scripts/facade_check.py [--write | --build-features]
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORE_TOML = ROOT / "Cargo.toml"
FACADE = ROOT / "crates" / "alice-physics"
FACADE_TOML = FACADE / "Cargo.toml"
FACADE_LIB = FACADE / "src" / "lib.rs"
PATHS_TEST = FACADE / "tests" / "facade_paths.rs"
SNAPSHOT = ROOT / "docs" / "PUBLIC_API_SNAPSHOT.txt"
IDENTITY_TEST = FACADE / "tests" / "facade_identity.rs"
ENGINE_PIN = ROOT / "tests" / "physics_semantics_id.rs"
UNITY = ROOT / "bindings" / "AlicePhysics.cs"
UNREAL = ROOT / "unreal-plugin" / "Source"
DLL_RE = re.compile(r'const string DLL = "([^"]+)";')
LIBFILE_RE = re.compile(r'"(?:lib)?([A-Za-z0-9_]+)\.(?:dll|dylib|so)"')
PIN_RE = re.compile(r'^const PINNED_ID_HEX: &str = "([0-9a-f]{64})";$', re.M)
CORE = "alice_physics_core"
DEP = "alice_physics_core"
ITEM_RE = re.compile(r"^pub (mod|use|struct|enum|trait|union|type|const|static|fn|unsafe fn|const fn|"
                     r"const unsafe fn|extern \"C\" fn|unsafe extern \"C\" fn) " + CORE + r"(::[A-Za-z0-9_]+)*")
HEADER = """//! Generated by scripts/facade_check.py --write from docs/PUBLIC_API_SNAPSHOT.txt: every
//! importable item of alice-physics-core's public API resolves through the facade's
//! `alice_physics` path. Run with the snapshot's features:
//!   cargo test -p alice-physics --features std,simd,parallel,ffi,gpu-solver-bridge
#![cfg(all(feature = "std", feature = "simd", feature = "parallel", feature = "ffi", feature = "gpu-solver-bridge"))]
#![allow(unused_imports, reason = "each import only has to resolve")]
#![allow(deprecated, reason = "deprecated items are public API too and must resolve")]
"""


def feature_problems(core: dict, facade: dict) -> tuple[list[str], int]:
    cf, ff = core.get("features", {}), facade.get("features", {})
    out = []
    for name in sorted(set(cf) - set(ff)):
        out.append(f"feature {name!r} of alice-physics-core is not forwarded by the facade")
    for name in sorted(set(ff) - set(cf)):
        out.append(f"the facade has feature {name!r}, which alice-physics-core does not")
    for name in sorted(set(cf) & set(ff)):
        want = list(cf[name]) if name == "default" else [f"{DEP}/{name}"]
        if list(ff[name]) != want:
            out.append(f"the facade's feature {name!r} is {ff[name]!r}, not {want!r}")
    return out, len(set(cf) | set(ff))


def dependency_problems(core: dict, facade: dict) -> list[str]:
    """the facade requires exactly the engine's version (they are published together)"""
    dep = facade.get("dependencies", {}).get(DEP, {})
    want = "=" + core.get("package", {}).get("version", "")
    if not isinstance(dep, dict) or dep.get("version") != want:
        return [f"the facade's dependency {DEP} is {dep!r}, not version {want!r}"]
    return []


def lib_problems(text: str) -> list[str]:
    code = re.sub(r"//[^\n]*", "", text)
    code = re.sub(r"#!?\[[^\]]*\]", "", code)
    items = [s.strip() for s in code.split(";") if s.strip()]
    if items != ["pub use alice_physics_core::*"]:
        return [f"crates/alice-physics/src/lib.rs must hold only `pub use alice_physics_core::*;`, found {items!r}"]
    return []


def pin_problems(identity: str, engine: str) -> tuple[list[str], int]:
    f, e = PIN_RE.findall(identity), PIN_RE.findall(engine)
    if len(f) != 1 or len(e) != 1:
        return [f"PINNED_ID_HEX: {len(f)} in crates/alice-physics/tests/facade_identity.rs and {len(e)} in "
                "tests/physics_semantics_id.rs, not one each"], 0
    if f != e:
        return [f"the facade's identity test pins {f[0][:8]}, the engine pins {e[0][:8]}"], 1
    return [], 1


def binding_problems(lib_name: str, unity: str, unreal: list[str]) -> tuple[list[str], int]:
    """the library names the engine bindings load, against the facade's lib name"""
    names = [n for n in DLL_RE.findall(unity) if n != "__Internal"]  # iOS links statically
    names += [n for text in unreal for n in LIBFILE_RE.findall(text)]
    out = [f"an engine binding loads `{n}`, not the facade's library `{lib_name}`" for n in sorted(set(names)) if n != lib_name]
    return out, len(names)


def importable(snapshot: str) -> list[str]:
    """the paths (after the crate name) of the modules and the module-level items"""
    found: list[tuple[str, str]] = []
    for line in snapshot.splitlines():
        m = ITEM_RE.match(line)
        if m:
            text = line.split(" " + CORE, 1)[1]
            p = re.match(r"((?:::[A-Za-z0-9_]+)*)", text).group(1)
            found.append((m.group(1), p.removeprefix("::")))
    mods = {p for k, p in found if k == "mod"}
    out = []
    for kind, p in found:
        if not p:
            continue
        parent = p.rsplit("::", 1)[0] if "::" in p else ""
        if kind == "mod" or parent in mods or parent == "":
            out.append(p)
    return sorted(set(out))


def render(paths: list[str]) -> str:
    body = "".join(f"use alice_physics::{p} as _;\n" for p in paths)
    return HEADER + "\n" + body + "\n#[test]\nfn every_core_item_resolves_through_the_facade() {\n" \
        f"    // {len(paths)} paths, checked at compile time\n" \
        "    assert_eq!(alice_physics::PHYSICS_SEMANTICS_ID, alice_physics_core::PHYSICS_SEMANTICS_ID);\n}\n"


def rustfmt(text: str) -> str:
    """the generated test as `cargo fmt` leaves it (the fmt gate formats every workspace member)"""
    r = subprocess.run(["rustfmt", "--edition", "2021", "--emit", "stdout"], input=text,
                       capture_output=True, text=True, cwd=ROOT)
    if r.returncode != 0:
        raise RuntimeError(f"rustfmt failed: {r.stderr.strip()[-300:]}")
    return r.stdout


def build_features() -> int:
    try:
        names = sorted(n for n in tomllib.loads(FACADE_TOML.read_text(encoding="utf-8")).get("features", {})
                       if n != "default")
    except (OSError, tomllib.TOMLDecodeError) as e:
        print(f"facade_check: {e}", file=sys.stderr)
        return 2
    failed = []
    for n in names:
        cmd = ["cargo", "check", "-p", "alice-physics", "--lib", "--features", n]
        print("+ " + " ".join(cmd), flush=True)
        if subprocess.run(cmd, cwd=ROOT).returncode != 0:
            failed.append(n)
    print(f"facade_check: {len(names)} features built through the facade, {len(failed)} failed {failed}")
    if not names:
        print("facade_check: built nothing", file=sys.stderr)
        return 2
    return 1 if failed else 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--write", action="store_true", help="regenerate crates/alice-physics/tests/facade_paths.rs")
    ap.add_argument("--build-features", action="store_true",
                    help="cargo check the facade with each of its features")
    a = ap.parse_args(argv)
    if a.build_features:
        return build_features()
    problems: list[str] = []
    try:
        core = tomllib.loads(CORE_TOML.read_text(encoding="utf-8"))
        facade = tomllib.loads(FACADE_TOML.read_text(encoding="utf-8"))
        lib = FACADE_LIB.read_text(encoding="utf-8")
        snapshot = SNAPSHOT.read_text(encoding="utf-8")
        identity = IDENTITY_TEST.read_text(encoding="utf-8")
        engine_pin = ENGINE_PIN.read_text(encoding="utf-8")
        unity = UNITY.read_text(encoding="utf-8")
        unreal = [p.read_text(encoding="utf-8") for p in sorted(UNREAL.rglob("*.Build.cs"))]
    except (OSError, tomllib.TOMLDecodeError) as e:
        print(f"facade_check: {e}", file=sys.stderr)
        return 2
    fp, nfeat = feature_problems(core, facade)
    problems += fp
    problems += lib_problems(lib)
    problems += dependency_problems(core, facade)
    pp, npin = pin_problems(identity, engine_pin)
    problems += pp
    bp, nbind = binding_problems(facade.get("lib", {}).get("name", ""), unity, unreal)
    problems += bp
    paths = importable(snapshot)
    try:
        want = rustfmt(render(paths))
    except (OSError, RuntimeError) as e:
        print(f"facade_check: {e}", file=sys.stderr)
        return 2
    if a.write:
        PATHS_TEST.parent.mkdir(parents=True, exist_ok=True)
        PATHS_TEST.write_text(want, encoding="utf-8")
    elif not PATHS_TEST.exists() or PATHS_TEST.read_text(encoding="utf-8") != want:
        problems.append("crates/alice-physics/tests/facade_paths.rs is not what the snapshot gives "
                        "(python3 scripts/facade_check.py --write)")
    for p in problems:
        print(f"error: {p}", file=sys.stderr)
    print(f"facade_check: {nfeat} features compared, {len(paths)} paths in the facade test, {npin} pin compared, {nbind} binding library names")
    if nfeat == 0 or not paths or npin == 0 or nbind == 0:
        print("facade_check: compared nothing", file=sys.stderr)
        return 2
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""The line-anchored `exclude_re` entries of `.cargo/mutants.toml`, generated from anchors
that name a function and a line offset in it.

cargo-mutants matches `exclude_re` against a mutant's name, which carries its line number
(`src/ccd.rs:151:13: replace * with / in sphere_plane_toi`), so an exclusion that must single
out one site of several in a function has to name the line. A line number goes stale when
code above it moves; the function and the offset in it do not. The anchors in
scripts/mutants-exclude-anchors.txt are the source:

    <file>\t<fn>\t<offset>[,<offset>...]\t<digest>[,<digest>...]\t<mutation regex>

`offset` is the 0-based line within the function (its `fn` line is 0), `digest` the first
16 hex digits of the SHA-256 of that line's text, stripped (the line the proof was written
about), and the mutation regex the part of the entry after `.*`. The generated entries sit
in `exclude_re` between the `# BEGIN line anchors` and `# END line anchors` comments, one
per anchor: `<file name>:<line>:.*<regex>` or `<file name>:(<l1>|<l2>):.*<regex>`.

  python3 scripts/mutants_exclude_lines.py --check   # CI: fails on any finding below
  python3 scripts/mutants_exclude_lines.py --write   # rewrite the block after code moved

Findings: a function not found, or not unique in its file; an anchored line whose text no
longer has the recorded digest (the code the proof was about changed: read it again and
update the anchor by hand); the block differs from what the anchors generate (run
--write); no anchor compared. --write also renames the generated entries in
scripts/mutants-exclude-baseline.txt, keeping their counts, and refuses to write while a
digest finding stands.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mutants_equivalent import fn_spans, line_digest  # noqa: E402

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
ANCHORS = "scripts/mutants-exclude-anchors.txt"
CONFIG = ".cargo/mutants.toml"
BASELINE = "scripts/mutants-exclude-baseline.txt"
BEGIN = "    # BEGIN line anchors: generated by scripts/mutants_exclude_lines.py, do not edit"
END = "    # END line anchors"


class Anchor:
    def __init__(self, file: str, fn: str, offsets: list[int], digests: list[str], regex: str):
        self.file, self.fn, self.offsets, self.digests, self.regex = file, fn, offsets, digests, regex


def parse_anchors(text: str) -> tuple[list[Anchor], list[str]]:
    anchors, findings = [], []
    for n, raw in enumerate(text.splitlines(), 1):
        if not raw.strip() or raw.startswith("#"):
            continue
        parts = raw.split("\t")
        if len(parts) != 5:
            findings.append(f"{ANCHORS}:{n}: expected 5 tab-separated fields, got {len(parts)}")
            continue
        file, fn, offs, digs, regex = parts
        try:
            offsets = [int(x) for x in offs.split(",")]
        except ValueError:
            findings.append(f"{ANCHORS}:{n}: offsets must be integers: {offs}")
            continue
        digests = digs.split(",")
        if len(digests) != len(offsets) or any(o < 0 for o in offsets):
            findings.append(f"{ANCHORS}:{n}: one digest per non-negative offset")
            continue
        anchors.append(Anchor(file, fn, offsets, digests, regex))
    return anchors, findings


def resolve(a: Anchor, root: Path) -> tuple[list[int] | None, list[str]]:
    """The 1-based lines of an anchor, or the findings that prevent it."""
    path = root / a.file
    if not path.is_file():
        return None, [f"{a.file}: no such file ({a.fn})"]
    src = path.read_text(encoding="utf-8")
    spans = fn_spans(src, a.fn)
    if len(spans) != 1:
        return None, [f"{a.file}: fn {a.fn} found {len(spans)} times, expected exactly once"]
    start, end, _ = spans[0]
    lines = src.splitlines()
    out, findings = [], []
    for off, dig in zip(a.offsets, a.digests):
        at = start + off
        if at > end:
            findings.append(f"{a.file}: {a.fn}+{off} is past the end of the function")
            continue
        if line_digest(lines[at]) != dig:
            findings.append(
                f"{a.file}: {a.fn}+{off} (line {at + 1}) no longer has the text the proof was "
                f"about (digest {line_digest(lines[at])}, recorded {dig}): read it again and "
                f"update the anchor"
            )
            continue
        out.append(at + 1)
    return (out if not findings else None), findings


def entry(a: Anchor, lines: list[int]) -> str:
    name = re.escape(Path(a.file).name)
    at = str(lines[0]) if len(lines) == 1 else "(" + "|".join(str(x) for x in lines) + ")"
    return f"{name}:{at}:.*{a.regex}"


def toml_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(anchors: list[Anchor], root: Path) -> tuple[list[str], list[str]]:
    entries, findings = [], []
    for a in anchors:
        lines, f = resolve(a, root)
        findings += f
        if lines is not None:
            entries.append(entry(a, lines))
    return entries, findings


def block_bounds(config: list[str]) -> tuple[int, int] | None:
    try:
        b = config.index(BEGIN)
        e = config.index(END, b)
    except ValueError:
        return None
    return b, e


def current_entries(config: list[str]) -> list[str] | None:
    bounds = block_bounds(config)
    if bounds is None:
        return None
    out = []
    for raw in config[bounds[0] + 1:bounds[1]]:
        m = re.fullmatch(r'\s*"((?:[^"\\]|\\.)*)",\s*', raw)
        if m is None:
            return None
        out.append(m.group(1).replace('\\"', '"').replace("\\\\", "\\"))
    return out


def run(root: Path, write: bool) -> list[str]:
    anchors, findings = parse_anchors((root / ANCHORS).read_text(encoding="utf-8"))
    if not anchors and not findings:
        return [f"{ANCHORS}: no anchor compared"]
    want, f = generate(anchors, root)
    findings += f
    config_path = root / CONFIG
    config = config_path.read_text(encoding="utf-8").splitlines()
    have = current_entries(config)
    if have is None:
        return findings + [f"{CONFIG}: the line-anchor block is missing or malformed"]
    if findings:
        return findings
    if want == have:
        return []
    if not write:
        return [f"{CONFIG}: the line-anchor block is stale (code moved): run {Path(__file__).name} --write"]
    b, e = block_bounds(config)
    config[b + 1:e] = [f"    {toml_string(x)}," for x in want]
    config_path.write_text("\n".join(config) + "\n", encoding="utf-8", newline="\n")
    renames = dict(zip(have, want)) if len(have) == len(want) else {}
    base_path = root / BASELINE
    base = base_path.read_text(encoding="utf-8").splitlines()
    for i, raw in enumerate(base):
        if "\t" in raw and not raw.startswith("#"):
            count, pat = raw.split("\t", 1)
            if pat in renames:
                base[i] = f"{count}\t{renames[pat]}"
    base_path.write_text("\n".join(base) + "\n", encoding="utf-8", newline="\n")
    return []


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true")
    g.add_argument("--write", action="store_true")
    ap.add_argument("--root", type=Path, default=ROOT)
    args = ap.parse_args(argv)
    anchors, _ = parse_anchors((args.root / ANCHORS).read_text(encoding="utf-8"))
    findings = run(args.root, args.write)
    print(f"MUTANTS-EXCLUDE-LINES: {{\"anchors\": {len(anchors)}, \"findings\": {len(findings)}}}")
    for f in findings:
        print(f"mutants-exclude-lines: {f}")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
